#!/bin/sh
# Writes lib/gen/api.dart, the one import (`package:app/gen/api.dart`) that
# re-exports every generated stub plus the OpenAPI client.
#
# It used to be a hand-written, committed file inside lib/gen; when lib/gen
# became gitignored (432a308) it went with it, so a fresh clone no longer
# compiled. It is derived from the generated tree instead, after `buf generate`
# and the OpenAPI client -- by `make buf-generate` / `make generate-openapi`
# and by frontend/Dockerfile.
#
# Only the .pbgrpc.dart of a service and the .pb.dart of everything else: a
# .pbgrpc.dart re-exports its own .pb.dart, and a .pb.dart its .pbenum.dart.
# Every proto shares `package music_room.v1`, so no two of them declare the
# same name.
#
# Usage: write_api_barrel.sh <lib/gen directory>
set -eu
gen=${1:?usage: write_api_barrel.sh <lib/gen directory>}
cd "$gen"
{
  echo '// GENERATED by frontend/app/tool/write_api_barrel.sh -- do not edit.'
  echo '// Re-exports every generated stub and the OpenAPI client.'
  find music_room -name '*.pb.dart' | sort | while read -r f; do
    grpc=${f%.pb.dart}.pbgrpc.dart
    if [ -f "$grpc" ]; then f=$grpc; fi
    echo "export 'package:app/gen/$f';"
  done
  if [ -f openapi_client/lib/api.dart ]; then
    echo "export 'package:app/gen/openapi_client/lib/api.dart';"
  fi
} > api.dart
